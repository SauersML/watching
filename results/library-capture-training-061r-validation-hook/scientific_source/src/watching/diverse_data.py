def make_diverse_data(task="probe", *, seed=20261017):
    """Return family-balanced splits with one explicitly identified paired overlap."""
    if task not in TRAIN_QUESTIONS:
        raise ValueError(f"Unknown task: {task}")
    rng = random.Random(seed)
    data = {split: [] for split in ("train", "validation", "test", "test_wording", "ood")}

    def row(context, family, index, question, wording_id):
        rendered_context = f"```python\n{context}\n```" if family == "short_code" else context
        return {
            "context": context,
            "text": f"{rendered_context}\n\n{question}",
            "family": family,
            "context_id": f"{family}:{index:02d}",
            "wording_id": wording_id,
        }

    for family_index, (family, contexts) in enumerate(CONTEXTS.items()):
        order = list(range(len(contexts)))
        rng.shuffle(order)
        for split, selected in (
            ("train", order[:32]),
            ("validation", order[32:40]),
            ("test", order[40:48]),
        ):
            for position, index in enumerate(selected):
                wording = (position + family_index) % 8
                context = contexts[index]
                data[split].append(
                    row(context, family, index, TRAIN_QUESTIONS[task][wording], f"train:{wording}")
                )
                if split == "test":
                    heldout = (position + family_index) % 4
                    data["test_wording"].append(
                        row(
                            context,
                            family,
                            index,
                            HELDOUT_QUESTIONS[task][heldout],
                            f"heldout:{heldout}",
                        )
                    )
    for family_index, (family, contexts) in enumerate(HELDOUT_CONTEXTS.items()):
        for index, context in enumerate(contexts):
            wording = (index + family_index) % 4
            data["ood"].append(
                row(context, family, index, HELDOUT_QUESTIONS[task][wording], f"heldout:{wording}")
            )
    prior = {context for contexts in OOD_CONTEXTS.values() for context in contexts}
    prior.update(r["context"] for rows in make_expanded_data().values() for r in rows)
    unique = [r["context"] for split, rows in data.items() if split != "test_wording" for r in rows]
    if len(unique) != len(set(unique)) or set(unique) & prior:
        raise ValueError("Contexts must be fresh and distinct outside paired wording transfer")
    return data


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--task", choices=tuple(TRAIN_QUESTIONS), required=True)
    parser.add_argument("--out", type=Path, required=True)
    parser.add_argument(
        "--tokenizer", help="Local or Hugging Face tokenizer for rendered length check"
    )
    parser.add_argument("--max-length", type=int, default=64)
    args = parser.parse_args()
    if args.max_length < 1:
        parser.error("max-length must be positive")
    data = make_diverse_data(args.task)
    if args.tokenizer:
        from transformers import AutoTokenizer

        lengths = rendered_lengths(data, AutoTokenizer.from_pretrained(args.tokenizer))
        maxima = {split: max(values) for split, values in lengths.items()}
        print(json.dumps({"task": args.task, "max_rendered_tokens": maxima}), flush=True)
        if max(maxima.values()) > args.max_length:
            parser.error(f"A prompt exceeds {args.max_length} tokens; truncation is forbidden")
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n")
    print(
        json.dumps(
            {
                "output": str(args.out),
                "counts": {s: len(r) for s, r in data.items()},
                "paired_transfer": "test_wording reuses test contexts; not independent",
            }
        ),
        flush=True,
    )


if __name__ == "__main__":
    main()
